package com.flick;

import com.flick.math.Exporters;
import com.flick.math.FitResult;

import java.util.HashSet;
import java.util.List;
import java.util.Set;

/**
 * Renders the whole library as one pasteable Kotlin file. Kept free of Android
 * imports so it can be unit-tested on a desktop JVM.
 */
public final class LibraryExport {
    private LibraryExport() {}

    public static String kotlin(List<SavedCurve> curves) {
        StringBuilder sb = new StringBuilder();
        sb.append("// Generated by Flick\n");
        sb.append("import androidx.compose.animation.core.CubicBezierEasing\n");
        sb.append("import androidx.compose.animation.core.Easing\n");
        sb.append("import androidx.compose.animation.core.spring\n\n");
        sb.append("object Motion {\n");
        if (curves == null || curves.isEmpty()) {
            sb.append("    // no curves saved yet\n");
        } else {
            // Two curves named "Snap" would produce a file that does not compile.
            Set<String> used = new HashSet<String>();
            for (SavedCurve c : curves) {
                String base = Exporters.identifier(c.name);
                String id = base;
                int n = 2;
                while (!used.add(id)) {
                    id = base + n;
                    n++;
                }
                FitResult f = c.toFit();
                sb.append(Exporters.kotlinConstant(id, f)).append('\n');
            }
        }
        sb.append("}\n");
        return sb.toString();
    }
}
